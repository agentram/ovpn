export function messages(language: Language): Messages {
  return language === "ru" ? ru : language === "zh" ? zh : en;
}
export type MessageKey = keyof typeof en;
export function errorMessage(error: unknown, language: Language): string {
  const text = error instanceof Error ? error.message : String(error);
  const t = messages(language);
  if (text.includes("SSH_HOST_UNREACHABLE")) return t.nodeUnavailable;
  if (text.includes("SSH_ACCESS_FAILED")) return t.sshAccessFailed;
  if (text.includes("SSH_HOST_KEY_CHANGED")) return t.hostKeyChanged;
  if (text.includes("DELIVERY_UNAVAILABLE")) return t.deliveryUnavailable;
  if (text.includes("USER_ASSIGNMENT_CONFLICT")) return t.assignmentConflict;
  if (text.includes("STALE_PLAN")) return t.stalePlan;
  if (text.includes("WORKSPACE_BUSY")) return t.busy;
  if (text.includes("WORKER")) return t.workerError;
  if (text.includes("OPERATION_UNAVAILABLE")) return t.operationUnavailable;
  return t.operationError;
}
